type PathDef = { d: string; x?: number; y?: number; fill?: boolean; strokeWidth?: number; winding?: "evenodd" };

function Icon({ paths, viewBox = "0 0 20 20" }: { paths: PathDef[]; viewBox?: string }) {
  return function Rendered(props: SVGProps<SVGSVGElement>) {
    return (
      <svg width="20" height="20" viewBox={viewBox} fill="none" {...props}>
        {paths.map((p, i) => (
          <path
            key={i}
            d={p.d}
            transform={p.x || p.y ? `translate(${p.x ?? 0} ${p.y ?? 0})` : undefined}
            fill={p.fill ? "currentColor" : "none"}
            stroke={p.fill ? "none" : "currentColor"}
            strokeWidth={p.strokeWidth ?? 1.5}
            strokeLinecap="round"
            strokeLinejoin="round"
            fillRule={p.winding}
          />
        ))}
      </svg>
    );
  };
}

